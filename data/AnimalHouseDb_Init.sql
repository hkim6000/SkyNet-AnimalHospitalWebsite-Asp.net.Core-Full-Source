CREATE PROCEDURE XSP_NEXT_NO
    @key NVARCHAR(20),
    @prefix NVARCHAR(10),
    @no NVARCHAR(20) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @y INT = YEAR(GETDATE());
    DECLARE @v INT;
    BEGIN TRANSACTION;
    UPDATE NUMBERSEQ SET SEQ_VALUE = CASE WHEN SEQ_YEAR = @y THEN SEQ_VALUE + 1 ELSE 1 END, SEQ_YEAR = @y WHERE SEQ_KEY = @key;
    IF @@ROWCOUNT = 0
    BEGIN
        INSERT INTO NUMBERSEQ (SEQ_KEY, SEQ_YEAR, SEQ_VALUE) VALUES (@key, @y, 1);
    END
    SELECT @v = SEQ_VALUE FROM NUMBERSEQ WHERE SEQ_KEY = @key;
    COMMIT TRANSACTION;
    SET @no = @prefix + CAST(@y AS NVARCHAR(4)) + N'-' + RIGHT(N'00000' + CAST(@v AS NVARCHAR(10)), 5);
END
GO

